"""Public-domain films too large to commit; fetch_demo_films caches them for seeding."""

from dataclasses import dataclass
import hashlib
from pathlib import Path
import shutil
from urllib.parse import quote
from urllib.request import urlopen

from django.conf import settings


@dataclass(frozen=True)
class DemoFilm:
    title: str
    item: str
    filename: str
    md5: str
    subtitle_filename: str = ""
    subtitle_name: str = ""

    @property
    def url(self):
        return f"https://archive.org/download/{self.item}/{quote(self.filename)}"

    @property
    def cache_path(self):
        return Path(settings.DEMO_FILMS_DIR) / self.filename


# Pinned by MD5 so a re-uploaded file on archive.org fails loudly instead of quietly
# changing the seed.
DEMO_FILMS = [
    DemoFilm(
        title="His Girl Friday (1940)",
        item="his_girl_friday",
        filename="his_girl_friday.mp4",
        md5="8527a3c6c69520b655fbc6e10f0c6e3f",
        subtitle_filename="his_girl_friday.asr.srt",
        subtitle_name="English (auto-generated by archive.org)",
    ),
    # archive.org's derived H.264 copy; the original upload is AV1, which Safari often
    # can't play.
    DemoFilm(
        title="Charade (1963)",
        item="charade-1963_202610",
        filename="Charade 1963.ia.mp4",
        md5="7c5b3f07923e141c2a38ba5abfb91f9d",
    ),
    DemoFilm(
        title="A Star Is Born (1937)",
        item="a-star-is-born-1937-720p-blu-rayx-64",
        filename="A Star Is Born (1937) Mp4.mp4",
        md5="5ab189b02b8b7e6b8214b08c2778c6d9",
        subtitle_filename="a_star_is_born_1937.en.sdh.srt",
        subtitle_name="English SDH",
    ),
]


def file_md5(path):
    digest = hashlib.md5(usedforsecurity=False)
    with open(path, "rb") as file:
        while chunk := file.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def fetch_film(film):
    """Download a film into the cache. Returns False if a verified copy was already there."""
    path = film.cache_path
    if path.exists() and file_md5(path) == film.md5:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    # Downloading beside the final name means an interrupted download is never seeded.
    partial = path.with_name(f"{path.name}.part")
    try:
        with urlopen(film.url, timeout=60) as response, open(partial, "wb") as out:
            shutil.copyfileobj(response, out, 1024 * 1024)
        actual = file_md5(partial)
        if actual != film.md5:
            raise ValueError(
                f"{film.url} has MD5 {actual}, expected {film.md5}. "
                "The file on archive.org changed; update DEMO_FILMS after checking it."
            )
        partial.replace(path)
    finally:
        partial.unlink(missing_ok=True)
    return True
