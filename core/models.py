def validate_imdb_id(id):
    """
    Accept an IMDb title ID or a generated internal Resource ID.

    IMDb title IDs begin with ``tt`` followed by at least seven digits. Resources
    that aren't listed in IMDb receive a ``BYU`` prefix followed by ten digits.
    """
    if re.fullmatch(r"(?:tt\d{7,}|BYU\d{10})", id or ""):
        return
    raise ValidationError(
        "Enter an IMDb title ID beginning with 'tt', or a generated BYU Resource ID."
    )


