    title = models.CharField(max_length=255)
    playlist = models.ForeignKey(
        Playlist,
        on_delete=models.CASCADE,
        related_name="contents",
        null=True,
        blank=True,
    )
    resource_file = models.ForeignKey(
        ResourceFile,
        on_delete=models.CASCADE,
        related_name="contents",
        null=True,
        blank=True,
    )
    resource = models.ForeignKey(
        Resource,
        on_delete=models.CASCADE,
        related_name="contents",
        null=True,
        blank=True,
    )
    annotation_set = models.ForeignKey(
        AnnotationSet,
        on_delete=models.SET_NULL,
        related_name="contents",
        null=True,
        blank=True,
    )
    url = models.URLField(max_length=500, blank=True, null=True)
    description = models.TextField(blank=True)
    allow_definitions = models.BooleanField(default=True)
    allow_notes = models.BooleanField(default=True)
    allow_captions = models.BooleanField(default=True)
    views = models.IntegerField(default=0, editable=False)
    published = models.BooleanField(default=False)
    words = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        unique_together = ("playlist", "title")

    def __str__(self):
        playlist_name = self.playlist.name if self.playlist else "No Playlist"
        return f"{self.title} | {playlist_name} | {self.id}"

    def save(self, *args, **kwargs):
        if self.resource_file:
            self.resource = self.resource_file.resource
        super().save(*args, **kwargs)

    def get_resource(self):
        if self.resource_id:
            return self.resource
        if self.resource_file_id:
            return self.resource_file.resource
        return None

    def is_url_only(self):
        return self.resource_file_id is None and bool(self.url)

    def get_available_annotation_sets(self):
        """Get all AnnotationSets available for this content's resource."""
        resource = self.get_resource()
        if not resource:
            return AnnotationSet.objects.none()
        return AnnotationSet.objects.filter(resource=resource)

    def get_subtitles(self):
        """
        Get all subtitles as list of dicts for the AnnotationPlayer.
        Each dict has the following keys:
            - 'srclang'
            - 'vtt' or 'url'
            - 'label'
        """
        resource = self.get_resource()
        if not resource:
            return []
        sub_objs = Subtitle.objects.filter(resource=resource)
        subtitles = [
            {
                "id": sub.pk,
                "srclang": sub.language.lang_tag,
                "vtt": sub.subtitles_file.read().decode("utf-8"),
                "name": sub.name,
            }
            for sub in sub_objs
        ]
        return subtitles

    def get_player_json(self):
        """
        Generate complete JSON data for AnnotationPlayer.loadData().
        Returns a dict with 'annotations', each containing JSON strings.
        """
        annotation_set_json = (
            self.annotation_set.to_player_json()
            if self.annotation_set
            else {"annotations": [], "tracks": []}
        )
        return {
            "annotations": annotation_set_json["annotations"],
            "tracks": annotation_set_json["tracks"],
            "subtitleTracks": self.get_subtitles(),
        }


